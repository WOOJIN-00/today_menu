// 같은 재료를 다르게 부르는 경우를 하나로 맞춘다 (예: "계란" → "달걀")
const INGREDIENT_ALIASES = {
  "계란": "달걀", "파": "대파", "참치": "참치캔", "햄": "스팸",
  "소세지": "소시지", "우동": "우동면", "국수": "소면", "빵": "식빵",
  "돼지": "돼지고기", "소": "소고기", "닭": "닭고기", "삼겹살": "돼지고기",
};

function normalizeIngredient(name) {
  const trimmed = String(name).replace(/\s+/g, "");
  return INGREDIENT_ALIASES[trimmed] || trimmed;
}

// 내 재료와 가장 많이 겹치는 레시피 3개를 골라 missing(부족한 재료)을 붙여 돌려준다.
// 겹치는 재료가 하나도 없는 레시피는 넣지 않는다. (그래서 3개보다 적거나 빈 목록일 수 있음)
// - mood: "든든" / "가벼움" / "매콤" / "국물" / "빠르게" / "" (상관없음)
// - excludeNames: 이미 추천한 메뉴 이름 (나중에 "다시 추천"에서 사용)
function recommendFromRecipes(userIngredients, mood = "", excludeNames = [], count = 3) {
  const have = new Set(userIngredients.map(normalizeIngredient));
  const matchesMood = (r) =>
    !mood || (mood === "빠르게" ? r.time_min <= 15 : r.tags.includes(mood));

  return RECIPES
    .filter((r) => !excludeNames.includes(r.name))
    .map((r) => {
      const missing = r.ingredients.filter((i) => !have.has(i));
      return {
        name: r.name,
        time_min: r.time_min,
        ingredients: r.ingredients,
        missing,
        steps: r.steps,
        matched: r.ingredients.length - missing.length,
        moodMatch: matchesMood(r),
      };
    })
    .filter((r) => r.matched > 0)
    // 정렬 순서: ① 겹치는 재료 많은 순 ② 기분이 맞는 것 ③ 부족한 재료 적은 순 ④ 조리 시간 짧은 순
    .sort((a, b) =>
      b.matched - a.matched ||
      Number(b.moodMatch) - Number(a.moodMatch) ||
      a.missing.length - b.missing.length ||
      a.time_min - b.time_min
    )
    .slice(0, count);
}

